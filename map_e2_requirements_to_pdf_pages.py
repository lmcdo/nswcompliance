def generate_sql(mappings):
    """Generate SQL to update database with page mappings"""

    sql_lines = [
        "-- Update E2 Haberfield requirements with PDF page mappings",
        "-- Generated by: map_e2_requirements_to_pdf_pages.py",
        "",
        "-- Backup first",
        "CREATE TABLE IF NOT EXISTS dcp_precinct_requirements_backup_e2_pdf AS",
        "SELECT * FROM dcp_precinct_requirements WHERE precinct_id = 'E2';",
        "",
        "-- Update requirements with PDF page numbers",
        ""
    ]

    for req_id, mapping in mappings.items():
        page = mapping['page']
        section = mapping['section']

        sql_lines.append(f"-- ID {req_id}: {section}")
        sql_lines.append(
            f"UPDATE dcp_precinct_requirements\n"
            f"SET\n"
            f"  pdf_pages = ARRAY[{page}],\n"
            f"  pdf_page_image_url = '/pdf-pages/leichhardt-e2/page_{page}.png'\n"
            f"WHERE id = {req_id};\n"
        )

    sql_lines.extend([
        "",
        "-- Verification query",
        "SELECT id, requirement_text, pdf_pages, pdf_page_image_url",
        "FROM dcp_precinct_requirements",
        "WHERE precinct_id = 'E2'",
        "ORDER BY id;",
    ])

    return '\n'.join(sql_lines)

