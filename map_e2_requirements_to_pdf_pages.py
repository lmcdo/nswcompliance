def load_e2_requirements():
    """Load E2 requirements from database"""
    conn = get_safe_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT id, requirement_text, category
        FROM dcp_precinct_requirements
        WHERE precinct_id = 'E2'
        ORDER BY id
    """)

    requirements = cursor.fetchall()
    cursor.close()
    conn.close()

    return [
        {'id': r[0], 'text': r[1], 'category': r[2]}
        for r in requirements
    ]

